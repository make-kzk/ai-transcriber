"""Бриф: что именно разобрать в разговоре и для кого.

Отделён от вызова модели намеренно. Здесь только данные и сборка текста —
это можно читать, править и проверять глазами, не тратя ни копейки.
"""

# Готовые сценарии. Первый — по умолчанию.
PRESETS = {
    "interview": {
        "label": "Собеседование кандидата",
        "roles": ["кандидат", "нанимающий менеджер"],
        "subject_hint": "название позиции",
        "focus": ["substance", "selfpresentation", "questions", "redflags", "fit"],
    },
    "vendor": {
        "label": "Оценка подрядчика или агентства",
        "roles": ["представитель подрядчика", "заказчик"],
        "subject_hint": "предмет закупки или услуги",
        "focus": ["substance", "structure", "redflags", "agreements"],
    },
    "internal": {
        "label": "Внутренняя встреча команды",
        "roles": ["участник", "руководитель"],
        "subject_hint": "тема встречи",
        "focus": ["structure", "agreements", "balance"],
    },
    "custom": {
        "label": "Свой вариант",
        "roles": ["собеседник", "ведущий разговор"],
        "subject_hint": "о чём разговор",
        "focus": ["structure", "substance", "agreements"],
    },
}

# Что можно попросить разобрать. Формулировки — то, что реально уйдёт в запрос.
FOCUS_OPTIONS = {
    "structure": ("Как был построен разговор",
                  "как разговор развивался: кто задавал направление, где терялся фокус, "
                  "что осталось необсуждённым"),
    "substance": ("Отвечал ли по существу",
                  "где ответы были конкретными — с цифрами, именами, сроками, — а где "
                  "оставались общими словами; приведи примеры того и другого"),
    "selfpresentation": ("Как себя подаёт",
                         "как собеседник рассказывает о своём опыте: опирается на "
                         "проверяемые факты или на самооценку"),
    "questions": ("Какие вопросы задавал",
                  "о чём спрашивал сам собеседник — это показывает, что для него важно "
                  "и насколько он разобрался в задаче"),
    "redflags": ("Настораживающие моменты",
                 "противоречия, уклончивые ответы, обещания без подтверждений — с "
                 "прямой цитатой и таймкодом на каждый случай"),
    "agreements": ("Договорённости и следующие шаги",
                   "о чём договорились, кто что делает и к какому сроку; отдельно — "
                   "что осталось непроговорённым"),
    "fit": ("Соответствие обсуждаемой роли",
            "насколько описанный опыт отвечает тому, что требуется на позиции"),
    "balance": ("Баланс участия",
                "кто вёл разговор, кому не хватило слова"),
}

SYSTEM = """Ты помогаешь HR-специалисту и нанимающему менеджеру разобрать
запись рабочего разговора.

Как писать:
— по-русски, простыми словами, как пишут коллеге, а не в отчёт для совета директоров;
— без кадрового жаргона: никаких «компетенций», «софт-скилов», «профиля кандидата»,
  «вовлечённости» и «синергии»;
— без общих оценок вроде «хорошо себя показал» — вместо них конкретный факт из
  разговора и что из него следует;
— каждое утверждение опирай на цитату с таймкодом в формате [ММ:СС];
— если данных для вывода не хватает, так и напиши, а не додумывай.

Чего не делать:
— не оценивай личные качества, характер и эмоции по тексту — их там нет;
— не делай выводов о пригодности человека: твоя работа собрать факты, решение
  принимает читатель;
— речевые метрики (темп, паузы, громкость) — это фон, а не доказательство. Быстрая
  речь не значит нервозность, паузы не значат неуверенность. Упоминай их, только
  если они подкрепляют что-то видимое в самом разговоре."""


def build(preset_key: str, roles: dict, subject: str, focus_keys: list,
          extra: str, metrics_text: str, transcript: str) -> tuple[str, str]:
    """Собирает (системная часть, запрос). Ничего не отправляет."""
    preset = PRESETS.get(preset_key, PRESETS["custom"])
    lines = [f"Тип разговора: {preset['label']}."]
    if subject.strip():
        lines.append(f"Предмет: {subject.strip()}.")
    if roles:
        who = "; ".join(f"{name} — {role}" for name, role in roles.items() if role)
        if who:
            lines.append(f"Кто есть кто: {who}.")
    lines.append("")
    lines.append("Разбери по пунктам:")
    for i, key in enumerate(focus_keys, 1):
        if key in FOCUS_OPTIONS:
            lines.append(f"{i}. {FOCUS_OPTIONS[key][0]} — {FOCUS_OPTIONS[key][1]}.")
    if extra.strip():
        lines.append("")
        lines.append(f"Дополнительно от заказчика разбора: {extra.strip()}")
    lines.append("")
    lines.append("В конце — короткий список того, что стоит уточнить "
                 "на следующей встрече.")
    lines.append("")
    lines.append("=" * 60)
    lines.append("РЕЧЕВЫЕ МЕТРИКИ (фон, не доказательство)")
    lines.append("=" * 60)
    lines.append(metrics_text)
    lines.append("")
    lines.append("=" * 60)
    lines.append("РАСШИФРОВКА")
    lines.append("=" * 60)
    lines.append(transcript)
    return SYSTEM, "\n".join(lines)
